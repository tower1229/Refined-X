import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import * as pagefind from 'pagefind';
import { buildSearchIndex, verifySearchIndex, writeSearchBundle } from './search-index.mjs';

async function fixture(t) {
	const root = await mkdtemp(path.join(os.tmpdir(), 'refined-x-search-'));
	t.after(() => rm(root, { recursive: true, force: true }));
	await writeFile(path.join(root, 'index.html'), '<html lang="en"><title>Search regression</title><body data-pagefind-body>Refined-X publishing telescope</body></html>');
	await mkdir(path.join(root, 'zh'));
	await writeFile(path.join(root, 'zh/index.html'), '<html lang="zh-CN"><title>搜索回归</title><body data-pagefind-body>OpenClaw 搜索入口回归测试</body></html>');
	return root;
}

test('real Pagefind API exports complete multilingual bundles across immediate shutdowns and repeated builds', async (t) => {
	const root = await fixture(t);
	// A real native backend on every iteration: no mocked ACK or generated bytes.
	for (let i = 0; i < 100; i++) {
		await buildSearchIndex(root);
		const result = await verifySearchIndex(path.join(root, 'pagefind'));
		assert.deepEqual(result.languages.sort(), ['en', 'zh-cn']);
		assert.ok(result.files > 10);
	}
});

test('disk gate rejects empty, malformed, missing, changed and unlisted files', async (t) => {
	const root = await fixture(t);
	await buildSearchIndex(root);
	const output = path.join(root, 'pagefind');
	const manifest = JSON.parse(await readFile(path.join(output, 'refined-x-manifest.json')));
	const entryPath = path.join(output, 'pagefind-entry.json');
	const original = await readFile(entryPath);
	for (const bytes of ['', '{', JSON.stringify({ version: '1.5.2', languages: {} })]) {
		await writeFile(entryPath, bytes);
		await assert.rejects(verifySearchIndex(output), /Pagefind/);
	}
	await writeFile(entryPath, original);
	for (const name of [manifest.files.find(f => f.path.endsWith('.pf_meta')).path, manifest.files.find(f => f.path.endsWith('.pf_index')).path, manifest.files.find(f => f.path.endsWith('.pf_fragment')).path, 'pagefind.js']) {
		const file = path.join(output, name); const bytes = await readFile(file);
		await rm(file); await assert.rejects(verifySearchIndex(output), /Pagefind/);
		await writeFile(file, Buffer.alloc(bytes.length, 97)); await assert.rejects(verifySearchIndex(output), /Pagefind/);
		await writeFile(file, bytes);
	}
	await writeFile(path.join(output, 'stale.js'), 'stale');
	await assert.rejects(verifySearchIndex(output), /Pagefind/);
});

test('writer validates real memory export, language references and gzip before accepting an index', async (t) => {
	const root = await fixture(t);
	const { index } = await pagefind.createIndex();
	let files;
	try { await index.addDirectory({ path: root }); ({ files } = await index.getFiles()); }
	finally { await pagefind.close(); }
	const replaceEntry = (entry) => files.map(file => file.path === 'pagefind-entry.json' ? { ...file, content: Buffer.from(JSON.stringify(entry)) } : file);
	const entry = JSON.parse(Buffer.from(files.find(f => f.path === 'pagefind-entry.json').content));
	const invalid = [
		files.map(f => f.path === 'pagefind-entry.json' ? { ...f, content: new Uint8Array() } : f),
		replaceEntry({ ...entry, languages: {} }),
		replaceEntry({ ...entry, languages: { en: { hash: 'missing', page_count: 1, wasm: 'en' } } }),
		files.filter(f => !f.path.endsWith('.pf_meta')),
		files.map(f => f.path.endsWith('.pf_fragment') ? { ...f, content: f.content.slice(0, 20) } : f),
		[...files, files[0]],
		[...files, { path: '../escape', content: Buffer.from('bad') }],
	];
	for (const bundle of invalid) await assert.rejects(writeSearchBundle(bundle, path.join(root, 'bad')), /Pagefind/);
});
